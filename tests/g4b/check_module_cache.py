"""PR1 (docs/G4B_SPEC.md section 7.8): `--module-cache DIR` module proof records, on the Python compiler and, with
--rs, on the Rust driver.

usage: check_module_cache.py WORK [--rs PATH] [--py PATH] [--only py|rs]
  --rs PATH: the Rust driver (adds the rs compiler); --py PATH: the pruvc.py to test (default pruvc/pruvc.py);
  --only: run one compiler. The Python compiler always runs unless --only rs.
Cases (each on each selected compiler, own directories): cold/warm reuse with identical output; a changed callee
ensures re-proves the caller and rejects; a changed imported body re-proves and rejects; swapped package aliases
re-prove and reject; a module named only inside a generic type argument stays in the closure; corrupt records are not reused; a failing single-file program gets no record; the
trust report carries `module_cache` only with the flag. Prints one line per failing check and
`module_cache: N/N passed`; exit 0 only if all pass."""
from pathlib import Path
import json
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
VALID = b"pruv-module-proof 1\nproved\n"
TOTAL = [0]
FAILS = []


def util(ens="result == x + 1", body="x + 1"):
    return "pub fn inc(x: i64) -> i64\n  requires 0 <= x && x <= 10\n  ensures %s\n{ return %s; }\n" % (ens, body)


APP = ("mod util;\npub fn f(x: i64) -> i64\n  requires 0 <= x && x <= 5\n  ensures result == x + 2\n"
       "{ return crate::util::inc(crate::util::inc(x)); }\n")
# package alias swap: `left` must resolve to the package whose v() is 0
SWAP_APP = ("mod left;\nmod right;\npub fn f() -> i64\n  ensures result == 0\n"
            "{ let a: i64 = crate::right::v(); return crate::left::v(); }\n")
# the root names `types` only inside `Option<...>`
NESTED_APP = ("mod types;\npub fn g(o: Option<crate::types::Flag>) -> i64\n  ensures result == 0\n{ return 0; }\n")
SINGLE_BAD = "pub fn f(x: i64) -> i64\n  requires 0 <= x && x <= 5\n  ensures result == x + 3\n{ return x + 1; }\n"


def check(name, ok, detail=""):
    TOTAL[0] += 1
    if not ok:
        FAILS.append("FAIL %s: %s" % (name, str(detail).strip()[-700:]))


def records(d):
    d = Path(d)
    return sorted(p for p in d.rglob("*") if p.is_file()) if d.is_dir() else []


def write(d, files):
    for rel, text in files.items():
        p = Path(d) / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)


class Comp:
    def __init__(self, label, cmd, work):
        self.label, self.cmd, self.work = label, cmd, work
        self.n = 0

    def run(self, d, root, cache=True, extra=()):
        """compile d/root to Rust source; returns (rc, text, generated bytes or None, trust report dict)"""
        self.n += 1
        out = Path(d) / ("out%d.rs" % self.n)
        tr = Path(d) / ("tr%d.json" % self.n)
        args = list(self.cmd) + [str(Path(d) / root), "-o", str(out), "--trust-report", str(tr)] + list(extra)
        if self.label == "py":
            args += ["--backend", "rust"]
        if cache:
            args += ["--module-cache", str(Path(d) / "mc")]
        c = subprocess.run(args, capture_output=True, text=True, timeout=600)
        rep = json.loads(tr.read_text()) if tr.exists() else {}
        gen = out.read_bytes() if out.exists() else None
        return c.returncode, c.stdout + c.stderr, gen, rep


def mc(rep):
    m = rep.get("module_cache", {})
    return (m.get("hits"), m.get("misses"), m.get("stores"))


def cases(c):
    L = c.label
    # cold / warm / identical output / report shape
    d = c.work / "cold_warm"
    write(d, {"app.pruv": APP, "util.pruv": util()})
    rc, t, g0, rep0 = c.run(d, "app.pruv", cache=False)
    check(L + " nocache accepts", rc == 0, t)
    check(L + " nocache report has no module_cache", "module_cache" not in rep0 and
          "module_cache" not in rep0.get("flags", {}), rep0)
    rc, t, g1, rep = c.run(d, "app.pruv")
    check(L + " cold accepts", rc == 0, t)
    check(L + " cold counts", mc(rep) == (0, 2, 2), mc(rep))
    check(L + " cold report flag", rep.get("flags", {}).get("module_cache") is True, rep.get("flags"))
    recs = records(d / "mc")
    check(L + " cold records", len(recs) == 2 and all(p.read_bytes() == VALID and p.parent.name == p.name[:2]
                                                         for p in recs), recs)
    rc, t, g2, rep = c.run(d, "app.pruv")
    check(L + " warm accepts", rc == 0, t)
    check(L + " warm counts", mc(rep) == (2, 0, 0), mc(rep))
    check(L + " output identical", g0 is not None and g0 == g1 == g2)

    # a changed callee ensures: the callee proves, the caller must be re-proved and rejected
    write(d, {"util.pruv": util("result == x + 2", "x + 2")})
    rc, t, _, rep = c.run(d, "app.pruv")
    check(L + " changed ensures rejects", rc != 0 and "verify" in t, t)
    check(L + " changed ensures counts", mc(rep) == (0, 2, 1), mc(rep))
    rc, t, _, rep = c.run(d, "app.pruv")
    check(L + " changed ensures rejects again", rc != 0, t)
    check(L + " changed ensures caller not stored", mc(rep) == (1, 1, 0), mc(rep))

    # a changed imported body that breaks its own ensures: re-proved and rejected
    write(d, {"util.pruv": util("result == x + 1", "x + 2")})
    rc, t, _, rep = c.run(d, "app.pruv")
    check(L + " changed import rejects", rc != 0 and "verify" in t, t)
    # the caller still proves against the unchanged contract (its key holds the new util digest); util is not stored
    check(L + " changed import counts", mc(rep) == (0, 2, 1), mc(rep))
    rc, t, _, rep = c.run(d, "app.pruv")
    check(L + " changed import rejects again", rc != 0 and "verify" in t and mc(rep) == (1, 1, 0), (rc, mc(rep), t))

    # back to the original: the old records are reused
    write(d, {"util.pruv": util()})
    rc, t, _, rep = c.run(d, "app.pruv")
    check(L + " restored accepts from records", rc == 0 and mc(rep) == (2, 0, 0), (rc, mc(rep), t))

    # corrupt records are never reused
    for p in records(d / "mc"):
        p.write_bytes(b"pruv-module-proof 1\nproved")
    rc, t, _, rep = c.run(d, "app.pruv")
    check(L + " corrupt not reused", rc == 0 and mc(rep) == (0, 2, 2), (rc, mc(rep), t))

    # package aliases swapped in the manifest: same files, other resolution, must reject
    d = c.work / "swap"
    man = lambda left, right: json.dumps({"name": "app", "version": "0.1.0", "root": "app.pruv", "dependencies": {
        "left": {"path": "../" + left, "version": "0.1"}, "right": {"path": "../" + right, "version": "0.1"}}})
    pkg = lambda n: json.dumps({"name": n, "version": "0.1.0", "root": n + ".pruv"})
    v = lambda k: "pub fn v() -> i64\n  ensures result == %d\n{ return %d; }\n" % (k, k)
    write(d, {"app/app.pruv": SWAP_APP, "app/pruv.json": man("alpha", "beta"),
              "alpha/pruv.json": pkg("alpha"), "alpha/alpha.pruv": v(0),
              "beta/pruv.json": pkg("beta"), "beta/beta.pruv": v(1)})
    m = ["--manifest", str(d / "app" / "pruv.json")]
    rc, t, _, rep = c.run(d, "app/app.pruv", extra=m)
    check(L + " swap base accepts", rc == 0 and mc(rep) == (0, 3, 3), (rc, mc(rep), t))
    rc, t, _, rep = c.run(d, "app/app.pruv", extra=m)
    check(L + " swap base warm", rc == 0 and mc(rep) == (3, 0, 0), (rc, mc(rep), t))
    write(d, {"app/pruv.json": man("beta", "alpha")})
    rc, t, _, rep = c.run(d, "app/app.pruv", extra=m)
    check(L + " swapped aliases reject", rc != 0 and "verify" in t, (rc, mc(rep), t))

    # a module mentioned only inside a generic type argument is still in the closure: a changed `types` (no
    # functions, so no record of its own) re-proves the root (audit finding: Rust read only whole identity strings, not `option<crate::types::Flag>`)
    d = c.work / "nested"
    write(d, {"app.pruv": NESTED_APP, "types.pruv": "pub enum Flag { A, B }\n"})
    rc, t, _, rep = c.run(d, "app.pruv")
    check(L + " nested base accepts", rc == 0 and mc(rep) == (0, 1, 1), (rc, mc(rep), t))
    rc, t, _, rep = c.run(d, "app.pruv")
    check(L + " nested base warm", rc == 0 and mc(rep) == (1, 0, 0), (rc, mc(rep), t))
    write(d, {"types.pruv": "pub enum Flag { A, B, C }\n"})
    rc, t, _, rep = c.run(d, "app.pruv")
    check(L + " nested type change re-proves root", rc == 0 and mc(rep) == (0, 1, 1), (rc, mc(rep), t))

    # a failing single-file program: one module, re-proved each time, never recorded
    d = c.work / "single"
    write(d, {"bad.pruv": SINGLE_BAD})
    for i in range(2):
        rc, t, _, rep = c.run(d, "bad.pruv")
        check(L + " single rejects %d" % i, rc != 0 and "verify" in t, t)
        check(L + " single no record %d" % i, records(d / "mc") == [] and mc(rep) == (0, 1, 0), mc(rep))


def main(argv):
    work = Path(argv[0])
    rs = py = only = None
    i = 1
    while i < len(argv):
        if argv[i] == "--rs":
            rs = argv[i + 1]
        elif argv[i] == "--py":
            py = argv[i + 1]
        elif argv[i] == "--only":
            only = argv[i + 1]
        else:
            print("unknown argument: " + argv[i])
            return 2
        i += 2
    base = work / "g4b_module_cache"
    if base.exists():
        shutil.rmtree(base)
    comps = []
    if only != "rs":
        comps.append(Comp("py", [sys.executable, str(Path(py).resolve() if py else ROOT / "pruvc" / "pruvc.py")],
                          base / "py"))
    if rs and only != "py":
        comps.append(Comp("rs", [rs], base / "rs"))
    for c in comps:
        cases(c)
    for f in FAILS:
        print(f)
    print("module_cache: %d/%d passed" % (TOTAL[0] - len(FAILS), TOTAL[0]))
    return 0 if not FAILS else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
