"""Generates pruvc-rs/crates/pruv-core/src/shared_tables.rs from pruvc/data/*.json.

python tools/gen_shared.py           write the file
python tools/gen_shared.py --check   exit 1 if the file is stale
"""
import json
import os
import sys

TABLES = ["mono_limits", "builtin_types", "shim_edges"]   # ordered; add new tables at the end

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = "pruvc-rs/crates/pruv-core/src/shared_tables.rs"


def _literal(value):
    if isinstance(value, bool):
        raise ValueError("unsupported value kind: bool")
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if (isinstance(value, list) and all(isinstance(v, list) and len(v) == 2 and all(isinstance(s, str) for s in v)
                                        for v in value)):
        return "&[" + ", ".join("(%s, %s)" % (json.dumps(a, ensure_ascii=False), json.dumps(b, ensure_ascii=False))
                                for a, b in value) + "]"
    if isinstance(value, list) and all(isinstance(v, str) for v in value):
        return "&[" + ", ".join(json.dumps(v, ensure_ascii=False) for v in value) + "]"
    raise ValueError("unsupported value kind: %r" % (value,))


def render():
    lines = [
        "//! Generated by tools/gen_shared.py from pruvc/data/*.json. Do not edit by hand.",
        "//! Python reads the same JSON at import (pruvc/shared_data.py); "
        "tests/check_generated.py fails when this file is stale.",
    ]
    for name in TABLES:
        path = os.path.join(ROOT, "pruvc", "data", name + ".json")
        with open(path, encoding="utf-8") as f:
            table = json.load(f)
        lines.append("")
        lines.append("/// " + table["doc"])
        lines.append("pub mod %s {" % table["rust_module"])
        for item in table["items"]:
            lines.append("    pub const %s: %s = %s;" % (item["name"], item["rust_type"], _literal(item["value"])))
        lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    path = os.path.join(ROOT, OUT)
    if "--check" in sys.argv[1:]:
        try:
            with open(path, "rb") as f:
                current = f.read()
        except OSError:
            current = None
        if current != text.encode("utf-8"):
            print("stale: %s; run tools/gen_shared.py" % OUT)
            return 1
        return 0
    with open(path, "wb") as f:
        f.write(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
